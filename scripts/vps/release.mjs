import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync, copyFileSync, createReadStream, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { SERVICES, RUNTIME_IMAGES, DEFAULT_DOMAIN, validateDomain, imageNames, composeConfig, nginxConfig, caddyComposeConfig, caddyConfig, envTemplate } from './config.mjs';

const require = createRequire(import.meta.url);
const yaml = require('js-yaml');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const args = process.argv.slice(2);
const option = (key, fallback) => { const i = args.indexOf(key); return i < 0 ? fallback : args[i + 1]; };
const domain = validateDomain(option('--domain', DEFAULT_DOMAIN));
const tag = option('--tag', 'vps-20261026');
const platform = option('--platform', 'linux/amd64');
if (!['linux/amd64', 'linux/arm64'].includes(platform)) throw new Error('Usa linux/amd64 o linux/arm64');
const images = imageNames(tag);
const output = resolve(root, option('--output', `artifacts/restoapp-${tag}`));
if (existsSync(join(output, 'manifest.json'))) throw new Error('La release ya tiene manifiesto; usa otro directorio/tag para no sobrescribirla.');
mkdirSync(join(output, 'ops'), { recursive: true });
mkdirSync(join(output, 'nginx'), { recursive: true });
mkdirSync(join(output, 'caddy'), { recursive: true });
writeFileSync(join(output, 'docker-compose.yml'), '# Generated by scripts/vps/release.mjs.\n' + yaml.dump(composeConfig(tag), { lineWidth: 140, noRefs: true }));
writeFileSync(join(output, 'docker-compose.caddy.yml'), yaml.dump(caddyComposeConfig(), { lineWidth: 140, noRefs: true }));
writeFileSync(join(output, '.env.example'), envTemplate(domain));
writeFileSync(join(output, 'nginx', 'restoapp.conf'), nginxConfig(domain));
writeFileSync(join(output, 'caddy', 'restoapp.files.caddyfile'), caddyConfig(domain, 'files'));
writeFileSync(join(output, 'caddy', 'restoapp.cloudflare.caddyfile'), caddyConfig(domain, 'cloudflare'));
for (const file of ['config.mjs', 'init-env.mjs', 'bootstrap-admin.cjs', 'migrate-domains.cjs', 'backup.sh']) copyFileSync(join(root, 'scripts/vps', file), join(output, 'ops', file));
copyFileSync(join(root, 'docs', 'DESPLIEGUE_VPS_MAVRICITAS.md'), join(output, 'README.md'));
copyFileSync(join(root, 'docs', 'DESPLIEGUE_VPS_CADDY.md'), join(output, 'CADDY.md'));
copyFileSync(join(root, 'docs', 'DESPLIEGUE_VPS_CADDY.md'), join(output, 'DESPLIEGUE_VPS_CADDY.md'));

function run(command, params, capture = false) {
  const result = spawnSync(command, params, { cwd: root, stdio: capture ? ['ignore', 'pipe', 'inherit'] : 'inherit', encoding: 'utf8' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} ${params[0]} terminó con código ${result.status}`);
  return result.stdout?.trim();
}
const manifest = { domain, platform, tag, createdAt: new Date().toISOString(), sourceRevision: run('git', ['rev-parse', 'HEAD'], true), dirtySource: !!run('git', ['status', '--porcelain'], true), images: [], runtime: RUNTIME_IMAGES, archive: null };
if (args.includes('--build')) {
  run('docker', ['version']);
  for (let i = 0; i < SERVICES.length; i++) {
    console.log(`[${i + 1}/${SERVICES.length + 2}] Building ${images[i]}`);
    run('docker', ['build', '--platform', platform, '--build-arg', `APP_NAME=servicio-${SERVICES[i]}`, '-t', images[i], '-f', 'Dockerfile', '.']);
  }
  run('docker', ['build', '--platform', platform, '--build-arg', 'VITE_API_BASE_URL=', '--build-arg', `VITE_TENANT_BASE_DOMAIN=${domain}`, '-t', images.at(-2), '-f', 'apps/pwa-cliente/Dockerfile', '.']);
  run('docker', ['build', '--platform', platform, '-t', images.at(-1), '-f', 'infra/kong/Dockerfile', 'infra/kong']);
}
if (args.includes('--build') || args.includes('--save')) {
  for (const name of images) manifest.images.push({ name, id: run('docker', ['image', 'inspect', '--format', '{{.Id}}', name], true) });
}
if (args.includes('--save')) {
  for (const name of RUNTIME_IMAGES) run('docker', ['pull', '--platform', platform, name]);
  const archive = join(output, 'images.tar');
  run('docker', ['image', 'save', '-o', archive, ...images, ...RUNTIME_IMAGES]);
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(archive)) hash.update(chunk);
  manifest.archive = { file: 'images.tar', sha256: hash.digest('hex') };
  writeFileSync(join(output, 'SHA256SUMS'), `${manifest.archive.sha256}  images.tar\n`);
}
writeFileSync(join(output, 'manifest.json'), JSON.stringify(manifest, null, 2));
console.log(`Release preparada: ${output}`);
console.log(args.includes('--save') ? 'Imágenes y configuración listas para transferir al VPS.' : 'Configuración preparada. Añade --build --save para compilar y exportar las imágenes.');
